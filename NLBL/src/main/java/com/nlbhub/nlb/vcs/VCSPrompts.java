package com.nlbhub.nlb.vcs;

/**
 * Вопросы к автору во время pull/push по ssh (вызываются из фонового потока): пароль к ключу и
 * подтверждение незнакомого сервера. Редактор показывает их в окнах; без редактора (тесты, консоль)
 * — свои ответы.
 */
public interface VCSPrompts {
    /**
     * Пароль к ключу ssh (зашифрованному); retry — прошлый не подошёл. null — отмена
     *
     * @param key     какой ключ — путь к его файлу (по нему пароль можно запомнить)
     * @param message текст вопроса JGit (с путём к ключу)
     */
    char[] askPassphrase(String key, String message, boolean retry);

    /**
     * Да или нет (сервер ssh ещё незнаком: доверять ли ему, запомнить ли его ключ)
     */
    boolean confirm(String message);

    /**
     * Сообщение (например, ключ сервера изменился — соединение отклонено)
     */
    void inform(String message);
}
